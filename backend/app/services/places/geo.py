# QA: границы региона MVP (south, west, north, east) — зона тайлов Valhalla.
# Тот же прямоугольник тянет сид (scripts/seed_places.py). Точка вне него —
# маршрут дня не строится, оптимизация падает «вне покрытия».
REGION_BBOX: tuple[float, float, float, float] = (54.30, 19.60, 55.35, 23.05)


def in_region(lat: float, lon: float) -> bool:
    south, west, north, east = REGION_BBOX
    return south <= lat <= north and west <= lon <= east


# дальше этого от центра — место уже не «в городе»
MAX_CITY_DISTANCE_M = 20_000


def haversine_m(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371000
    dlat, dlon = radians(lat2 - lat1), radians(lon2 - lon1)
    a = sin(dlat / 2) ** 2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon / 2) ** 2
    return 2 * r * asin(sqrt(a))


def nearest_city(lat: float, lon: float) -> str | None:
    """Ближайший город региона или None, если до всех дальше 20 км."""
    best_name, best_distance = None, None
    for name, city_lat, city_lon in REGION_CITIES:
        distance = haversine_m(lat, lon, city_lat, city_lon)
        if best_distance is None or distance < best_distance:
            best_name, best_distance = name, distance
    if best_distance is not None and best_distance <= MAX_CITY_DISTANCE_M:
        return best_name
    return None
